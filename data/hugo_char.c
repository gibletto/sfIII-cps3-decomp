/*
 * HUGO_CHAR.C  Hugo's animation scripts and sprite part tables
 *
 * The animation scripts Hugo's moves run, one table per kind of script (nmca, dmca, btca, caca,
 * cuca, atca, exca, saca), each an index of scripts followed by the scripts. set_char_base_data
 * (CHARID) installs the tables as char_table[]; set_char_move_init starts script
 * char_table[kind][index] and char_move steps it: a frame line shows sprite `number` for `ctr`
 * frames with its sound, hit boxes (hit, a row of hugo_hit_ix_table), attack (att, a row of
 * hugo_catt_table) and effect; a command line (CM_ codes) jumps, loops, tests and sets. See
 * charscr.h for the line layouts and the kind numbers a command's koc names.
 *
 * olc_ix_table and overlap_char_tbl place the extra sprite parts a frame overlays (its olc field);
 * rival_catch_tbl positions a caught opponent for each throw frame (its rival field).
 */

